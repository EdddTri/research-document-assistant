def build_cases(papers=None, case_fixtures=None):
    papers = PAPERS if papers is None else papers
    case_fixtures = fixtures() if case_fixtures is None else case_fixtures
    with session_factory("agent")() as db:
        documents = {}
        evidence = {}
        for name, (digest, url) in papers.items():
            doc = db.scalar(select(Document).where(Document.sha256 == digest, Document.status == "ready")
                            .order_by(Document.version.desc()))
            if doc is None:
                raise ValueError(f"Upload/index the verified public {name} paper edition before preparing this suite: {url}")
            documents[name] = doc
            evidence[name] = list(db.scalars(select(Content).where(Content.document_id == doc.id)))
        result = []
        for fixture in case_fixtures:
            groups, sources = [], []
            for name, pages in fixture["locations"].items():
                if not pages:
                    continue
                ids = [item.id for item in evidence[name] if item.page in pages]
                if not ids:
                    raise ValueError(f"Missing reference page evidence for {fixture['id']}")
                groups.append(ids)
                sources.extend({"document_id": documents[name].id, "page": page} for page in pages)
            expected = {key: fixture[key] for key in ("reference_answer", "assertions", "answerability",
                         "requires_code", "code_spec", "exact_output", "forbidden_strings") if key in fixture}
            expected.update(evidence_groups=groups, sources=sources,
                            prompt_injection=fixture.get("prompt_injection", False))
            result.append({"id": fixture["id"], "split": "development", "manually_verified": True,
                           "reference_review": "Assistant reviewed original PDF native text and captions; not independently human-adjudicated",
                           "category": fixture["category"],
                           "source_versions": {name: {"sha256": documents[name].sha256, "version": documents[name].version,
                                                      "url": papers[name][1]} for name in fixture["papers"]},
                           "inputs": {"schema_version": "1", "question": fixture["question"],
                                      "document_ids": [documents[name].id for name in fixture["papers"]],
                                      "history": fixture.get("history", [])}, "expected": expected})
        return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    cases = build_cases()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(json.dumps(case, ensure_ascii=False) + "\n" for case in cases), encoding="utf-8")
    print(f"Prepared {len(cases)} source-reviewed development cases: {args.output}")


if __name__ == "__main__":
    main()
